#!/usr/bin/env python3
"""Download PARMA 4.10 from JAEA and set it up for UCMuon (spectrum mode 3).

PARMA (T. Sato, Japan Atomic Energy Agency) is not part of UCMuon. JAEA allows
its use for non-commercial purposes only and asks for citations, terms that an
MIT-licensed archive cannot carry, so each user fetches JAEA's own packages and
this script builds from them the three things UCMuon needs:

  data/EXPACS/parma/                JAEA's parma.zip, unpacked (data tables)
  src/parma/parma_subroutines.f90   JAEA's subroutines.f90 with UCMuon's edits
  ucmugen/include/UCMuGen_PARMA.h   generated from parma_cpp.zip by
                                    ucmugen/tools/make_parma_header.py

All three are git-ignored; the two zips are kept in external/parma/. Then
rebuild the generator (make local, or setup.sh, which runs this script first).

  python3 tools/install_parma.py                 show JAEA's terms, ask, install
  python3 tools/install_parma.py --yes           no question (scripts, CI)
  python3 tools/install_parma.py --zip-dir DIR   use parma.zip and parma_cpp.zip
                                                 already downloaded into DIR
  python3 tools/install_parma.py --status        is PARMA installed?

The two code files are checked against the SHA-256 values of the PARMA 4.10
release UCMuon was tested with (tools/parma_v4.10.sha256). If JAEA has changed
them, nothing is installed (--force installs anyway; the edits may then fail).
Changed data tables are installed with a warning, since results for dates
after the end of the old tables would differ from published ones.
"""
from __future__ import annotations

import argparse
import hashlib
import io
import re
import shutil
import subprocess
import sys
import urllib.request
import zipfile
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
URL = "https://phits.jaea.go.jp/expacs/data/"
PAGE = "https://phits.jaea.go.jp/expacs/download-eng.htm"
CACHE = ROOT / "external" / "parma"
DATA_DIR = ROOT / "data" / "EXPACS" / "parma"
F90_OUT = ROOT / "src" / "parma" / "parma_subroutines.f90"
HEADER_OUT = ROOT / "ucmugen" / "include" / "UCMuGen_PARMA.h"
HEADER_TOOL = ROOT / "ucmugen" / "tools" / "make_parma_header.py"
MANIFEST = Path(__file__).resolve().parent / "parma_v4.10.sha256"
STAMP = DATA_DIR / "UCMUON_INSTALL.txt"

TERMS = """\
  PARMA 4.10 (T. Sato, Japan Atomic Energy Agency) provides spectrum mode 3.
  It is downloaded from JAEA (https://phits.jaea.go.jp/expacs/), not shipped
  with UCMuon, and comes with JAEA's conditions for use:
    - free for non-commercial use, redistribution and modification;
      commercial use needs a prior agreement with JAEA;
    - publications using it must cite T. Sato, PLoS ONE 10(12): e0144679
      (2015) and PLoS ONE 11(8): e0160390 (2016), and the URL above;
    - send a copy of such publications to nsed-expacs@jaea.go.jp.
  Everything else in UCMuon works without it."""

F90_HEADER = """\
!=============================================================================
! parma_subroutines.f90: PARMA 4.10 subroutines (T. Sato, JAEA) as used by
! UCMuon. GENERATED by tools/install_parma.py from subroutines.f90 of JAEA's
! parma.zip (https://phits.jaea.go.jp/expacs/). It is not part of UCMuon, not
! tracked by git, and not covered by UCMuon's MIT licence.
!
! Copyright (c) 2006 Japan Atomic Energy Agency (JAEA). All Rights Reserved.
! Conditions for use (https://phits.jaea.go.jp/expacs/):
!   - free to use, redistribute and modify for non-commercial purposes;
!     commercial use requires a prior agreement with JAEA;
!   - publications must cite T. Sato, PLoS ONE 10(12): e0144679 (2015) and
!     PLoS ONE 11(8): e0160390 (2016), and acknowledge the URL above;
!   - send a copy of any publication to nsed-expacs@jaea.go.jp;
!   - JAEA is not liable for any loss or damage from its use.
!
! UCMuon's edits (made by tools/install_parma.py):
!   - 'use parma_path' in the routines that open data files, and
!     file='input/...' replaced by trim(parma_datadir)//'input/...', so the
!     data directory is set by parma_set_datadir() (parma_path_module.f90);
!   - getHP: only years inside each FFP table count as data. Later years held
!     the 0.0 they were initialised to, which passed as "data exist" (ic=1,
!     W=0); they now fall through to ic=4 and the generator uses the latest W.
!=============================================================================
"""

# getHP: the two tests that took a year beyond the end of a table for data.
FFP_EDITS = [
    ("if(FFP(iy0,im0,id0).gt.-99.0) then ! data exist\n",
     "! UCMuon: years outside the tables keep the 0.0 they were initialised to,\n"
     "! which passed as \"data exist\" (ic=1, W=0) for any date after the last year\n"
     "! of FFPtable.day. Only years inside each table count as data now; later\n"
     "! years fall through to ic=4 and the generator uses the latest W instead.\n"
     "if(iy0.ge.iystart.and.iy0.le.iyend.and.FFP(iy0,im0,id0).gt.-99.0) then ! data exist\n"),
    ("if(FFPuso(iy0).gt.-99.0) then\n",
     "if(iy0.ge.iysUs.and.iy0.le.iyeUs.and.FFPuso(iy0).gt.-99.0) then\n"),
]
ROUTINE = re.compile(r"^\s*((real\*8|integer|double precision)\s+)?(function|subroutine)\s+\w+",
                     re.IGNORECASE)
N_ROUTINES_WITH_FILES, N_FILE_OPENS = 19, 43     # in PARMA 4.10's subroutines.f90


class InstallError(Exception):
    pass


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def read_manifest() -> dict[str, str]:
    out = {}
    for line in MANIFEST.read_text().splitlines():
        if line.strip() and not line.startswith("#"):
            digest, name = line.split(None, 1)
            out[name.strip()] = digest
    return out


def patch_fortran(src: str) -> str:
    """JAEA's subroutines.f90 -> src/parma/parma_subroutines.f90."""
    lines = src.replace("\r\n", "\n").splitlines(keepends=True)
    starts = [i for i, ln in enumerate(lines) if ROUTINE.match(ln)] + [len(lines)]
    out, n_use = lines[:starts[0]], 0
    for a, b in zip(starts[:-1], starts[1:]):
        body = lines[a:b]
        out.append(body[0])
        if any("file='input/" in ln for ln in body):
            out.append("use parma_path\n")
            n_use += 1
        out.extend(body[1:])
    text = "".join(out)
    n_open = text.count("file='input/")
    text = text.replace("file='input/", "file=trim(parma_datadir)//'input/")
    if (n_use, n_open) != (N_ROUTINES_WITH_FILES, N_FILE_OPENS):
        raise InstallError(f"subroutines.f90 has {n_use} routines with {n_open} data-file opens, "
                           f"expected {N_ROUTINES_WITH_FILES} and {N_FILE_OPENS}")
    for old, new in FFP_EDITS:
        if text.count(old) != 1:
            raise InstallError(f"getHP edit: found {text.count(old)} copies of {old.strip()!r}")
        text = text.replace(old, new)
    return F90_HEADER + text


def member_root(zf: zipfile.ZipFile, marker: str) -> str:
    """Directory prefix inside the zip of the shallowest file called marker."""
    hits = sorted((n for n in zf.namelist() if n.rsplit("/", 1)[-1] == marker),
                  key=lambda n: n.count("/"))
    if not hits:
        raise InstallError(f"{marker} not found in {zf.filename}")
    return hits[0][: -len(marker)]


def check_zip(zf: zipfile.ZipFile, pkg: str, code: str, manifest: dict, force: bool) -> list[str]:
    """Check the code file (fatal unless force) and the input/ tables
    (returned as a list of changed or missing names)."""
    root = member_root(zf, code)
    got = sha256(zf.read(root + code))
    if got != manifest[f"{pkg}/{code}"]:
        msg = (f"{code} in {pkg}.zip is not the PARMA 4.10 file UCMuon was tested with "
               f"(SHA-256 {got[:16]}...).")
        if not force:
            raise InstallError(msg + " JAEA may have released a new version; nothing was "
                               "installed. Re-run with --force to try anyway.")
        print("  WARNING: " + msg + " Continuing (--force).")
    changed = []
    for name, digest in manifest.items():
        if not name.startswith("parma/input/"):
            continue
        rel = name[len("parma/"):]
        try:
            if sha256(zf.read(root + rel)) != digest:
                changed.append(rel)
        except KeyError:
            changed.append(rel + " (missing)")
    return changed


def fetch(name: str, zip_dir: Path | None) -> bytes:
    if zip_dir is not None:
        path = zip_dir / name
        if not path.is_file():
            raise InstallError(f"{path} not found")
        return path.read_bytes()
    cached = CACHE / name
    if cached.is_file():
        print(f"  using {cached.relative_to(ROOT)} (downloaded earlier)")
        return cached.read_bytes()
    print(f"  downloading {URL}{name} ...")
    try:
        with urllib.request.urlopen(URL + name, timeout=120) as r:
            data = r.read()
    except OSError as e:
        raise InstallError(
            f"download of {URL}{name} failed ({e}). Download parma.zip and parma_cpp.zip "
            f"by hand from {PAGE} into one folder and run: "
            f"python3 tools/install_parma.py --zip-dir FOLDER") from e
    CACHE.mkdir(parents=True, exist_ok=True)
    cached.write_bytes(data)
    return data


def extract(zf: zipfile.ZipFile, root: str, dest: Path) -> None:
    """Unpack the members under root into dest (no paths outside dest)."""
    dest = dest.resolve()
    for info in zf.infolist():
        if not info.filename.startswith(root) or info.is_dir():
            continue
        target = (dest / info.filename[len(root):]).resolve()
        if dest not in target.parents:
            raise InstallError(f"unsafe path in zip: {info.filename}")
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(zf.read(info))


def installed() -> bool:
    return F90_OUT.is_file() and HEADER_OUT.is_file() and (DATA_DIR / "input").is_dir()


def install(zip_dir: Path | None, force: bool) -> None:
    manifest = read_manifest()
    zf = zipfile.ZipFile(io.BytesIO(fetch("parma.zip", zip_dir)))
    zf.filename = "parma.zip"
    zc = zipfile.ZipFile(io.BytesIO(fetch("parma_cpp.zip", zip_dir)))
    zc.filename = "parma_cpp.zip"
    changed = check_zip(zf, "parma", "subroutines.f90", manifest, force)
    changed_cpp = check_zip(zc, "parma_cpp", "subroutines.cpp", manifest, force)

    root = member_root(zf, "subroutines.f90")
    f90 = patch_fortran(zf.read(root + "subroutines.f90").decode("ascii"))
    extract(zf, root, DATA_DIR)
    F90_OUT.write_text(f90)

    cpp_dir = CACHE / "parma_cpp"
    shutil.rmtree(cpp_dir, ignore_errors=True)
    extract(zc, member_root(zc, "subroutines.cpp"), cpp_dir)
    res = subprocess.run([sys.executable, str(HEADER_TOOL), str(cpp_dir), "-o", str(HEADER_OUT)],
                         capture_output=True, text=True)
    if res.returncode != 0:
        raise InstallError("make_parma_header.py failed:\n" + res.stdout + res.stderr)

    STAMP.write_text(
        f"Installed by tools/install_parma.py on {date.today().isoformat()} from JAEA's\n"
        f"parma.zip (SHA-256 {sha256(zf.fp.getvalue())}) and\n"
        f"parma_cpp.zip (SHA-256 {sha256(zc.fp.getvalue())}).\n"
        f"Data tables changed from the tested PARMA 4.10 set: "
        f"{', '.join(sorted(set(changed + changed_cpp))) or 'none'}\n")
    print(f"  OK  data tables in {DATA_DIR.relative_to(ROOT)}/")
    print(f"  OK  {F90_OUT.relative_to(ROOT)} (JAEA code with UCMuon's edits)")
    print(f"  OK  {HEADER_OUT.relative_to(ROOT)}")
    for what, lst in (("parma.zip", changed), ("parma_cpp.zip", changed_cpp)):
        if lst:
            print(f"  WARNING: {len(lst)} data table(s) in {what} differ from the tested PARMA 4.10 "
                  f"set ({', '.join(lst[:4])}{', ...' if len(lst) > 4 else ''}). Results for dates "
                  f"after the old tables end can differ from published ones.")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--yes", action="store_true", help="install without asking")
    ap.add_argument("--zip-dir", type=Path, help="folder holding parma.zip and parma_cpp.zip")
    ap.add_argument("--force", action="store_true", help="install even if JAEA's code changed")
    ap.add_argument("--status", action="store_true", help="report whether PARMA is installed")
    a = ap.parse_args(argv)

    if a.status:
        print("PARMA installed" if installed() else "PARMA not installed")
        return 0 if installed() else 1
    print(TERMS)
    if not a.yes and sys.stdin.isatty():
        ans = input("  Download PARMA from JAEA now? [Y/n] ").strip().lower()
        if ans not in ("", "y", "yes"):
            print("  PARMA skipped (spectrum mode 3 unavailable; "
                  "run python3 tools/install_parma.py to add it later)")
            return 0
    try:
        install(a.zip_dir, a.force)
    except InstallError as e:
        print(f"  ERROR: {e}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
