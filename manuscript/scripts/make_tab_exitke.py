#!/usr/bin/env python3
"""Write manuscript/tab_exitke.tex, the mean exit kinetic energy table, from
the shipped six-code summary benchmark/results/benchmark_summary_v2.csv
(Geant4 standard-rock run, PHITS, and the four UCMuon engines on the six
monoenergetic beams).

Usage:  python3 manuscript/scripts/make_tab_exitke.py
"""
from __future__ import annotations

import csv
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SUMMARY = REPO / "benchmark" / "results" / "benchmark_summary_v2.csv"
OUT = REPO / "manuscript" / "tab_exitke.tex"
CODES = ["Geant4", "PHITS", "MUSIC", "PROPOSAL", "BB", "UCMuon"]
HEAD = [r"\geantfour{}", r"\phits{}", r"\music{}", r"\proposal{}", "Bethe--Bloch", "UCMuon-MC"]


def main() -> int:
    ke: dict[str, dict[int, float]] = {}
    with open(SUMMARY) as fh:
        for r in csv.DictReader(fh):
            ke.setdefault(r["Code"], {})[round(float(r["DepthCm"]) / 100)] = float(r["MeanExitKE_GeV"])
    depths = sorted(ke["Geant4"])
    lines = [
        "% Generated by manuscript/scripts/make_tab_exitke.py from",
        "% benchmark/results/benchmark_summary_v2.csv (do not edit by hand).",
        r"\begin{table}[ht]",
        r"\centering",
        r"\caption{Mean exit kinetic energy (GeV) of surviving muons for the UCMuon",
        r"  standard benchmark (six monoenergetic vertical beams at 5/10/20/50/100/300\,GeV,",
        r"  $10^5$ each; Standard Rock, $\rho=2.65$\,g\,cm$^{-3}$; $N=6\times10^5$). The mean",
        r"  is dominated by the high-energy beams that survive to depth. Bottom rows give",
        r"  the difference of each code from \geantfour{}.}",
        r"\label{tab:exitke}",
        r"\begin{tabular}{lcccccc}",
        r"\toprule",
        "$d$ [m] & " + " & ".join(HEAD) + r" \\",
        r"\midrule",
        r"\multicolumn{7}{l}{\textit{Mean exit kinetic energy [GeV]}} \\",
    ]
    for d in depths:
        lines.append(f"{d:<3d} & " + " & ".join(f"{ke[c][d]:.2f}" for c in CODES) + r" \\")
    lines += [r"\midrule", r"\multicolumn{7}{l}{\textit{Difference from \geantfour{} [\%]}} \\"]
    for d in depths:
        g = ke["Geant4"][d]
        lines.append(f"{d:<3d} & ---   & " + " & ".join(f"${(ke[c][d] / g - 1) * 100:+.1f}$" for c in CODES[1:]) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    OUT.write_text("\n".join(lines))
    print(f"[ok] wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
