#!/usr/bin/env python3
"""Write manuscript/tab_inclined.tex: the inclined-beam benchmark, survival and
mean exit kinetic energy of Geant4 and the other codes' relative difference
from it, per zenith angle and slant length, summed over the six beams.

Reads benchmark/results/inclined_beams_20261027.csv
(benchmark/analysis/inclined_summary.py).

    python3 manuscript/scripts/make_tab_inclined.py
"""
from __future__ import annotations

import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CSV = ROOT / "benchmark" / "results" / "inclined_beams_20261027.csv"
OUT = ROOT / "manuscript" / "tab_inclined.tex"
THETAS = (60, 80, 85)
L_M = (10, 25, 50, 100, 200)
CODES = (("PHITS", r"\phits{}"), ("MUSIC", r"\music{}"), ("PROPOSAL", r"\proposal{}"),
         ("Bethe-Bloch", "Bethe--Bloch"), ("UCMuon-MC", "UCMuon-MC"))


def main() -> None:
    v = {}
    for r in csv.DictReader(line for line in open(CSV) if not line.startswith("#")):
        if r["beam_GeV"] == "all":
            v[(r["code"], round(float(r["theta_deg"])), int(r["L_m"]))] = (
                float(r["survival_pct"]), float(r["exitKE_mean_GeV"]) if r["exitKE_mean_GeV"] else None)

    def diff(code, th, L, i):
        if (code, th, L) not in v:
            return "---"
        x, g = v[(code, th, L)][i], v[("Geant4", th, L)][i]
        return f"${100 * (x / g - 1):+.1f}$"

    out = [
        "% Generated by manuscript/scripts/make_tab_inclined.py from",
        "% benchmark/results/inclined_beams_20261027.csv (do not edit by hand).",
        r"\begin{table}[ht]",
        r"\centering",
        r"\caption{Inclined beams: the six monoenergetic beams of Table~\ref{tab:survival}"
        r" tilted to the zenith angle $\theta$ and scored at the slant length $L$"
        r" (planes at the depth $L\cos\theta$), summed over the beams ($6\times10^5$"
        r" muons). \geantfour{}'s survival and mean exit kinetic energy, and the"
        r" other codes' difference from them. The engines transport each muon"
        r" along the fixed path $L$, so their results are those of the vertical"
        r" beams at the same $L$.}",
        r"\label{tab:inclined}",
        r"\begin{tabular}{rrcccccc}",
        r"\toprule",
        r"$\theta$ & $L$ [m] & \geantfour{} & " + " & ".join(lab for _, lab in CODES) + r" \\",
        r"\midrule",
    ]
    for i, (title, fmt) in enumerate(((r"Survival [\%] and difference from \geantfour{} [\%]", "{:.2f}"),
                                      (r"Mean exit kinetic energy [GeV] and difference [\%]", "{:.1f}"))):
        out.append(r"\multicolumn{8}{l}{\textit{" + title + r"}} \\")
        for th in THETAS:
            for j, L in enumerate(L_M):
                g = v[("Geant4", th, L)][i]
                cells = [f"${th}^\\circ$" if j == 0 else "", str(L), fmt.format(g)]
                cells += [diff(code, th, L, i) for code, _ in CODES]
                out.append(" & ".join(cells) + r" \\")
            out.append(r"\addlinespace" if th != THETAS[-1] else "")
        if i == 0:
            out.append(r"\midrule")
    out += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    OUT.write_text("\n".join(line for line in out if line != "") + "\n")
    print(f"[ok] {OUT}")


if __name__ == "__main__":
    main()
